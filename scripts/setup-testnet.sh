#!/usr/bin/env bash
# Fresh Bonded v2 testnet deployment: creates the contract account, four role
# sub-accounts, two scoped agent keys, and initial bond pools.
# Requires: near-cli, cargo (wasm target), a funded account for sub-account
# creation. NOTE: the testnet faucet has a per-account daily rate limit; use
# an existing funded parent account instead of --useFaucet for sub-accounts.
#
# Usage:
#   PARENT_ACCOUNT=your.testnet CONTRACT_ID=bonded-v2.testnet ./scripts/setup-testnet.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONTRACT_ID="${CONTRACT_ID:-bonded-v2.testnet}"
PARENT_ACCOUNT="${PARENT_ACCOUNT:-}"
BUYER_ACCOUNT="${BUYER_ACCOUNT:-buyer-v2.testnet}"
FORGE_ACCOUNT="${FORGE_ACCOUNT:-ag-a.$CONTRACT_ID}"
SABLE_ACCOUNT="${SABLE_ACCOUNT:-agent-v2-6659.testnet}"
EVALUATOR_ACCOUNT="${EVALUATOR_ACCOUNT:-evaluator.$CONTRACT_ID}"
STORE="${AGENT_KEY_STORE:-/tmp/opencode/agent-keys}"
mkdir -p "$STORE"

echo "== Bonded v2 setup =="
echo "contract:  $CONTRACT_ID"
echo "parent:    ${PARENT_ACCOUNT:-<none>}"

for tool in near cargo git; do
  command -v "$tool" >/dev/null 2>&1 || { echo "missing tool: $tool" >&2; exit 1; }
done

create_account() {
  local account="$1"
  if near state "$account" >/dev/null 2>&1; then
    echo "exists: $account"
    return
  fi
  if [ -n "$PARENT_ACCOUNT" ]; then
    near create-account "$account" --masterAccount "$PARENT_ACCOUNT" --initialBalance "${INITIAL_BALANCE:-5}"
  else
    # Fallback: faucet (rate-limited). Prefer PARENT_ACCOUNT.
    near create-account "$account" --useFaucet
  fi
}

create_account "$CONTRACT_ID"
create_account "$BUYER_ACCOUNT"
create_account "$FORGE_ACCOUNT"
create_account "$SABLE_ACCOUNT"
create_account "$EVALUATOR_ACCOUNT"

echo "building contract"
cargo build \
  --manifest-path "$ROOT/contracts/bonded/Cargo.toml" \
  --target wasm32-unknown-unknown \
  --release

WASM="$ROOT/contracts/bonded/target/wasm32-unknown-unknown/release/bonded_contract.wasm"

if near view "$CONTRACT_ID" get_config '{}' >/dev/null 2>&1; then
  echo "contract already initialized; skipping deploy"
else
  echo "deploying contract"
  near deploy "$CONTRACT_ID" "$WASM" \
    --initFunction new \
    --initArgs "{\"owner\":\"$CONTRACT_ID\",\"evaluator\":\"$EVALUATOR_ACCOUNT\"}"
fi

# Pool deposits (full-access keys; scoped keys cannot attach deposits).
echo "funding bond pools"
near call "$CONTRACT_ID" deposit_bond '{}' --accountId "$FORGE_ACCOUNT" --deposit 2 --gas 30000000000000 || true
near call "$CONTRACT_ID" deposit_bond '{}' --accountId "$SABLE_ACCOUNT" --deposit 2 --gas 30000000000000 || true

# Scoped function-call keys for both demo agents (bids + submits only).
for agent in "$FORGE_ACCOUNT" "$SABLE_ACCOUNT"; do
  key_file="$STORE/$(echo "$agent" | tr '/' '_').json"
  if [ -f "$key_file" ]; then
    echo "key exists: $agent"
    continue
  fi
  echo "issuing scoped key for $agent"
  AGENT_KEY_STORE="$STORE" AGENT_ACCOUNT_HOST="$agent" "$ROOT/scripts/scoped-key.sh" "$agent" 0.5
done

FORGE_SEC="$(python3 -c "import json; print(json.load(open('$STORE/$(echo "$FORGE_ACCOUNT" | tr '/' '_').json'))['secret_key'])")"
FORGE_PUB="$(python3 -c "import json; print(json.load(open('$STORE/$(echo "$FORGE_ACCOUNT" | tr '/' '_').json'))['public_key'])")"
SABLE_SEC="$(python3 -c "import json; print(json.load(open('$STORE/$(echo "$SABLE_ACCOUNT" | tr '/' '_').json'))['secret_key'])")"
SABLE_PUB="$(python3 -c "import json; print(json.load(open('$STORE/$(echo "$SABLE_ACCOUNT" | tr '/' '_').json'))['public_key'])")"

cat > "$ROOT/.env" <<EOF
# Generated by scripts/setup-testnet.sh. Never commit this file.
CONTRACT_ID=$CONTRACT_ID
NEAR_NETWORK=testnet
BUYER_ACCOUNT=$BUYER_ACCOUNT
AGENT_A_ACCOUNT=$FORGE_ACCOUNT
AGENT_B_ACCOUNT=$SABLE_ACCOUNT
EVALUATOR_ACCOUNT=$EVALUATOR_ACCOUNT
AGENT_A_PRIVATE_KEY=$FORGE_SEC
AGENT_B_PRIVATE_KEY=$SABLE_SEC
AGENT_A_PUBLIC_KEY=$FORGE_PUB
AGENT_B_PUBLIC_KEY=$SABLE_PUB
AGENT_RUNTIME=opencode
RUST_LOG=bonded_api=info,tower_http=info
EOF
chmod 600 "$ROOT/.env"

echo
echo "== ready =="
echo "contract:   $CONTRACT_ID"
echo "buyer:      $BUYER_ACCOUNT"
echo "agents:     $FORGE_ACCOUNT, $SABLE_ACCOUNT"
echo "evaluator:  $EVALUATOR_ACCOUNT"
echo
echo "start the API:  cargo run --manifest-path services/api/Cargo.toml"
echo "start the web:  pnpm --dir apps/web dev"
echo "smoke test:     ./scripts/smoke.sh"
